        let helperMeta = #"{"type":"session_meta","payload":{"id":"helper-1","cwd":"/tmp/shot","originator":"codex_work_desktop","source":{"subagent":{"thread_spawn":{}}},"thread_source":"subagent","parent_thread_id":"01a12fbc-aaaa-bbbb-cccc-0123456789ab","agent_role":"API Tester"}}"#
