import XCTest
@testable import NikoCore

/// Fixtures mirror the shape of real transcripts (keys and nesting were read
/// from Claude Code 2.1 and Codex 0.160 files); the text in them is made up.
final class TranscriptParsingTests: XCTestCase {
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    private func jsonl(_ lines: [String]) -> Data { Data((lines.joined(separator: "\n") + "\n").utf8) }

    private func claude(_ lines: [String], quietFor: TimeInterval = 2, firstPrompt: String? = nil) -> TranscriptSnapshot {
        ClaudeTranscript.snapshot(path: "/h/.claude/projects/-tmp-proj/0f0e-session.jsonl", tail: jsonl(lines), tailIsWholeFile: true,
                                  firstPrompt: firstPrompt, modified: now.addingTimeInterval(-quietFor), now: now)!
    }

    private let prompt = #"{"type":"user","sessionId":"s","cwd":"/tmp/proj","entrypoint":"claude-desktop","timestamp":"2027-01-15T08:00:00.000Z","message":{"role":"user","content":"Fix the flaky upload test"}}"#
    private let toolUse = #"{"type":"assistant","timestamp":"2027-01-15T08:00:02.000Z","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"text","text":"Let me look."},{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"swift test --filter Upload"}}]}}"#
    private let toolResult = #"{"type":"user","toolUseResult":{"stdout":"ok"},"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]}}"#
    private let done = #"{"type":"assistant","timestamp":"2027-01-15T08:00:09.000Z","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"All green now."}]}}"#

    func testClaudeTurnIsFollowedStepByStep() {
        var snapshot = claude([prompt])
        XCTAssertEqual(snapshot.key, SessionKey(source: "claude", sessionID: "0f0e-session"))
        XCTAssertEqual(snapshot.phase, .working)
        XCTAssertEqual(snapshot.activity, .thinking)
        XCTAssertEqual(snapshot.lastPrompt, "Fix the flaky upload test")
        XCTAssertEqual(snapshot.cwd, "/tmp/proj")
        XCTAssertEqual(snapshot.host, .claudeDesktop)

        snapshot = claude([prompt, toolUse])
        XCTAssertEqual(snapshot.phase, .working)
        XCTAssertEqual(snapshot.activity, Activity(verb: "running", detail: "swift test --filter Upload"))
        XCTAssertEqual(snapshot.lastReply, "Let me look.")

        snapshot = claude([prompt, toolUse, toolResult])
        XCTAssertEqual(snapshot.activity, .thinking)

        snapshot = claude([prompt, toolUse, toolResult, done])
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.activity, .waiting)
        XCTAssertEqual(snapshot.lastReply, "All green now.")
        XCTAssertEqual(snapshot.phaseSince, Date(timeIntervalSince1970: 1_800_000_009))
    }

    func testClaudeNoiseIsNotMistakenForThePerson() {
        let meta = #"{"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: the messages below were generated by the user while running local commands."}}"#
        let command = #"{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>"}}"#
        let sidechain = #"{"type":"user","isSidechain":true,"message":{"role":"user","content":"Explore the repo for upload code"}}"#
        let title = #"{"type":"custom-title","customTitle":"Upload fix","sessionId":"s"}"#
        let name = #"{"type":"agent-name","agentName":"Generated name","sessionId":"s"}"#
        let snapshot = claude([prompt, done, meta, command, sidechain, name, title])
        XCTAssertEqual(snapshot.lastPrompt, "Fix the flaky upload test")
        XCTAssertEqual(snapshot.phase, .waiting, "none of those started a turn")
        XCTAssertEqual(snapshot.title, "Upload fix", "a title the user set wins over a generated one")
        XCTAssertEqual(claude([prompt, name]).title, "Generated name")
        XCTAssertEqual(claude([done], firstPrompt: "The very first ask").firstPrompt, "The very first ask")
    }

    func testClaudeQuestionInterruptionAndSilence() {
        let ask = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"tool_use","id":"q","name":"AskUserQuestion","input":{"questions":[]}}]}}"#
        XCTAssertEqual(claude([prompt, ask]).phase, .needsAttention)
        XCTAssertEqual(claude([prompt, ask]).activity.verb, "has a question")

        let interrupted = #"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user]"}]}}"#
        XCTAssertEqual(claude([prompt, toolUse, interrupted]).phase, .waiting)

        // A tool that has been "running" for half an hour without a byte written is not running.
        XCTAssertEqual(claude([prompt, toolUse], quietFor: 30 * 60).phase, .waiting)
        XCTAssertEqual(claude([prompt, toolUse], quietFor: 5 * 60).phase, .working, "long commands are normal")
        // Nothing recognisable in the tail: recent writes mean work, old ones mean idle.
        XCTAssertEqual(claude([#"{"type":"file-history-snapshot"}"#], quietFor: 5).phase, .working)
        XCTAssertEqual(claude([#"{"type":"file-history-snapshot"}"#], quietFor: 600).phase, .waiting)
    }

    func testClaudeBeingTurnedAwayAtALimitIsReadFromItsTranscript() {
        // As Claude Code writes it when the plan's window is used up (keys from a real file).
        let resets = Int(now.timeIntervalSince1970) + 5400
        let refused = #"{"type":"assistant","timestamp":"2027-01-15T08:00:03.000Z","isApiErrorMessage":true,"apiError":"usage_limit_reached","apiErrorStatus":429,"error":"rate_limit","apiErrorParams":{"rate_limit_info":{"status":"rejected","resetsAt":RESETS,"rateLimitType":"five_hour","overageStatus":"rejected","isUsingOverage":false}},"quotaLimits":{"status":"rejected","resetsAt":RESETS,"rateLimitType":"five_hour"},"message":{"role":"assistant","content":[{"type":"text","text":"You've hit your session limit"}]}}"#
            .replacingOccurrences(of: "RESETS", with: String(resets))
        var snapshot = claude([prompt, refused], quietFor: 30)
        XCTAssertEqual(snapshot.limitReached, RateLimitWindow(id: "five_hour", usedPercent: 100, resetsAt: Date(timeIntervalSince1970: Double(resets))))
        XCTAssertEqual(snapshot.limitReached?.minutes, 300)
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.activity.verb, "hit its limit")

        // The person tries again: the row is about that again, the window is still full.
        snapshot = claude([prompt, refused, prompt, toolUse], quietFor: 2)
        XCTAssertEqual(snapshot.phase, .working)
        XCTAssertEqual(snapshot.activity.verb, "running")
        XCTAssertNotNil(snapshot.limitReached)

        // Once the window has opened again there is nothing left to report.
        let later = ClaudeTranscript.snapshot(path: "/h/.claude/projects/-tmp-proj/0f0e-session.jsonl", tail: jsonl([prompt, refused]), tailIsWholeFile: true,
                                              modified: now, now: now.addingTimeInterval(6000))
        XCTAssertNil(later?.limitReached)
        XCTAssertEqual(later?.activity, .waiting)
        // An "allowed" notice is not a refusal.
        let allowed = refused.replacingOccurrences(of: "\"status\":\"rejected\"", with: "\"status\":\"allowed_warning\"")
        XCTAssertNil(claude([prompt, allowed]).limitReached)
    }

    func testClaudeHugeLinesAreClassifiedWithoutParsing() {
        let blob = String(repeating: "x", count: TranscriptText.parseLimit + 10)
        let huge = #"{"type":"user","toolUseResult":{"file":"\#(blob)"},"message":{"role":"user","content":[{"type":"tool_result","content":"…"}]}}"#
        let snapshot = claude([prompt, toolUse, huge])
        XCTAssertEqual(snapshot.activity, .thinking, "the tool came back")
        // A tail read starts in the middle of a line; that fragment is dropped, not parsed.
        let partial = ClaudeTranscript.snapshot(path: "/h/x/abc.jsonl", tail: jsonl(["tent\":\"half a line\"}}", done]),
                                                modified: now, now: now)
        XCTAssertEqual(partial?.phase, .waiting)
        XCTAssertEqual(ClaudeTranscript.firstPrompt(head: jsonl([#"{"type":"user","isMeta":true,"message":{"content":"x"}}"#, prompt])),
                       "Fix the flaky upload test")
    }

    // MARK: Codex

    private let codexPath = "/h/.codex/sessions/2027/01/15/rollout-2027-01-15T08-00-00-01a12fbc-aaaa-bbbb-cccc-0123456789ab.jsonl"
    private let metaLine = #"{"timestamp":"2027-01-15T08:00:00.000Z","type":"session_meta","payload":{"id":"01a12fbc-aaaa-bbbb-cccc-0123456789ab","cwd":"/tmp/shot","originator":"Codex Desktop","source":"vscode","cli_version":"0.160.0"}}"#
    private let started = #"{"timestamp":"2027-01-15T08:00:01.000Z","type":"event_msg","payload":{"type":"task_started","turn_id":"t"}}"#
    private let userMessage = #"{"timestamp":"2027-01-15T08:00:01.100Z","type":"response_item","payload":{"type":"message","role":"user","content":[{"type":"input_text","text":"Add a share sheet"}]}}"#
    private let exec = #"{"timestamp":"2027-01-15T08:00:03.000Z","type":"response_item","payload":{"type":"custom_tool_call","name":"exec","call_id":"c1","input":"xcodebuild -scheme Shot build\nsecond line"}}"#
    private let execOut = #"{"timestamp":"2027-01-15T08:00:05.000Z","type":"response_item","payload":{"type":"custom_tool_call_output","call_id":"c1","output":"ok"}}"#
