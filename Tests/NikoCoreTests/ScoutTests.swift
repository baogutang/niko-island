        XCTAssertTrue(helper.isSubagent)
        XCTAssertEqual(helper.parentID, "01a12fbc-aaaa-bbbb-cccc-0123456789ab")
        XCTAssertEqual(helper.title, "API Tester")
        XCTAssertEqual(helper.key.sessionID, "helper-1")
        // No session_meta in reach: the id comes from the file name.
        XCTAssertEqual(codex([started], head: [started]).key.sessionID, "01a12fbc-aaaa-bbbb-cccc-0123456789ab")
    }
