import XCTest
@testable import NikoCore

/// Fixtures mirror the shape of real transcripts (keys and nesting were read
/// from Claude Code 2.1 and Codex 0.160 files); the text in them is made up.
final class TranscriptParsingTests: XCTestCase {
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    private func jsonl(_ lines: [String]) -> Data { Data((lines.joined(separator: "\n") + "\n").utf8) }

    private func claude(_ lines: [String], quietFor: TimeInterval = 2, firstPrompt: String? = nil) -> TranscriptSnapshot {
        ClaudeTranscript.snapshot(path: "/h/.claude/projects/-tmp-proj/0f0e-session.jsonl", tail: jsonl(lines), tailIsWholeFile: true,
                                  firstPrompt: firstPrompt, modified: now.addingTimeInterval(-quietFor), now: now)!
    }

    private let prompt = #"{"type":"user","sessionId":"s","cwd":"/tmp/proj","entrypoint":"claude-desktop","timestamp":"2027-01-15T08:00:00.000Z","message":{"role":"user","content":"Fix the flaky upload test"}}"#
    private let toolUse = #"{"type":"assistant","timestamp":"2027-01-15T08:00:02.000Z","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"text","text":"Let me look."},{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"swift test --filter Upload"}}]}}"#
    private let toolResult = #"{"type":"user","toolUseResult":{"stdout":"ok"},"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"ok"}]}}"#
    private let done = #"{"type":"assistant","timestamp":"2027-01-15T08:00:09.000Z","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"All green now."}]}}"#

    func testClaudeTurnIsFollowedStepByStep() {
        var snapshot = claude([prompt])
        XCTAssertEqual(snapshot.key, SessionKey(source: "claude", sessionID: "0f0e-session"))
        XCTAssertEqual(snapshot.phase, .working)
        XCTAssertEqual(snapshot.activity, .thinking)
        XCTAssertEqual(snapshot.lastPrompt, "Fix the flaky upload test")
        XCTAssertEqual(snapshot.cwd, "/tmp/proj")
        XCTAssertEqual(snapshot.host, .claudeDesktop)

        snapshot = claude([prompt, toolUse])
        XCTAssertEqual(snapshot.phase, .working)
        XCTAssertEqual(snapshot.activity, Activity(verb: "running", detail: "swift test --filter Upload"))
        XCTAssertEqual(snapshot.lastReply, "Let me look.")

        snapshot = claude([prompt, toolUse, toolResult])
        XCTAssertEqual(snapshot.activity, .thinking)

        snapshot = claude([prompt, toolUse, toolResult, done])
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.activity, .waiting)
        XCTAssertEqual(snapshot.lastReply, "All green now.")
        XCTAssertEqual(snapshot.phaseSince, Date(timeIntervalSince1970: 1_800_000_009))
    }

    func testClaudeNoiseIsNotMistakenForThePerson() {
        let meta = #"{"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: the messages below were generated by the user while running local commands."}}"#
        let command = #"{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>"}}"#
        let sidechain = #"{"type":"user","isSidechain":true,"message":{"role":"user","content":"Explore the repo for upload code"}}"#
        let title = #"{"type":"custom-title","customTitle":"Upload fix","sessionId":"s"}"#
        let name = #"{"type":"agent-name","agentName":"Generated name","sessionId":"s"}"#
        let snapshot = claude([prompt, done, meta, command, sidechain, name, title])
        XCTAssertEqual(snapshot.lastPrompt, "Fix the flaky upload test")
        XCTAssertEqual(snapshot.phase, .waiting, "none of those started a turn")
        XCTAssertEqual(snapshot.title, "Upload fix", "a title the user set wins over a generated one")
        XCTAssertEqual(claude([prompt, name]).title, "Generated name")
        XCTAssertEqual(claude([done], firstPrompt: "The very first ask").firstPrompt, "The very first ask")
    }

    func testClaudeQuestionInterruptionAndSilence() {
        let ask = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"tool_use","id":"q","name":"AskUserQuestion","input":{"questions":[]}}]}}"#
        XCTAssertEqual(claude([prompt, ask]).phase, .needsAttention)
        XCTAssertEqual(claude([prompt, ask]).activity.verb, "has a question")

        let interrupted = #"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user]"}]}}"#
        XCTAssertEqual(claude([prompt, toolUse, interrupted]).phase, .waiting)

        // A tool that has been "running" for half an hour without a byte written is not running.
        XCTAssertEqual(claude([prompt, toolUse], quietFor: 30 * 60).phase, .waiting)
        XCTAssertEqual(claude([prompt, toolUse], quietFor: 5 * 60).phase, .working, "long commands are normal")
        // Nothing recognisable in the tail: recent writes mean work, old ones mean idle.
        XCTAssertEqual(claude([#"{"type":"file-history-snapshot"}"#], quietFor: 5).phase, .working)
        XCTAssertEqual(claude([#"{"type":"file-history-snapshot"}"#], quietFor: 600).phase, .waiting)
    }

    func testClaudeHugeLinesAreClassifiedWithoutParsing() {
        let blob = String(repeating: "x", count: TranscriptText.parseLimit + 10)
        let huge = #"{"type":"user","toolUseResult":{"file":"\#(blob)"},"message":{"role":"user","content":[{"type":"tool_result","content":"…"}]}}"#
        let snapshot = claude([prompt, toolUse, huge])
        XCTAssertEqual(snapshot.activity, .thinking, "the tool came back")
        // A tail read starts in the middle of a line; that fragment is dropped, not parsed.
        let partial = ClaudeTranscript.snapshot(path: "/h/x/abc.jsonl", tail: jsonl(["tent\":\"half a line\"}}", done]),
                                                modified: now, now: now)
        XCTAssertEqual(partial?.phase, .waiting)
        XCTAssertEqual(ClaudeTranscript.firstPrompt(head: jsonl([#"{"type":"user","isMeta":true,"message":{"content":"x"}}"#, prompt])),
                       "Fix the flaky upload test")
    }

    // MARK: Codex

    private let codexPath = "/h/.codex/sessions/2027/01/15/rollout-2027-01-15T08-00-00-01a12fbc-aaaa-bbbb-cccc-0123456789ab.jsonl"
    private let metaLine = #"{"timestamp":"2027-01-15T08:00:00.000Z","type":"session_meta","payload":{"id":"01a12fbc-aaaa-bbbb-cccc-0123456789ab","cwd":"/tmp/shot","originator":"Codex Desktop","source":"vscode","cli_version":"0.160.0"}}"#
    private let started = #"{"timestamp":"2027-01-15T08:00:01.000Z","type":"event_msg","payload":{"type":"task_started","turn_id":"t"}}"#
    private let userMessage = #"{"timestamp":"2027-01-15T08:00:01.100Z","type":"response_item","payload":{"type":"message","role":"user","content":[{"type":"input_text","text":"Add a share sheet"}]}}"#
    private let exec = #"{"timestamp":"2027-01-15T08:00:03.000Z","type":"response_item","payload":{"type":"custom_tool_call","name":"exec","call_id":"c1","input":"xcodebuild -scheme Shot build\nsecond line"}}"#
    private let execOut = #"{"timestamp":"2027-01-15T08:00:05.000Z","type":"response_item","payload":{"type":"custom_tool_call_output","call_id":"c1","output":"ok"}}"#
    private let complete = #"{"timestamp":"2027-01-15T08:00:09.000Z","type":"event_msg","payload":{"type":"task_complete","turn_id":"t","last_agent_message":"Share sheet added."}}"#

    private func codex(_ lines: [String], head: [String]? = nil, quietFor: TimeInterval = 2) -> TranscriptSnapshot {
        let meta = CodexTranscript.meta(path: codexPath, head: jsonl(head ?? [metaLine, started, userMessage]))
        return CodexTranscript.snapshot(path: codexPath, meta: meta, tail: jsonl(lines), tailIsWholeFile: true,
                                        modified: now.addingTimeInterval(-quietFor), now: now)!
    }

    func testCodexTurnIsFollowedStepByStep() {
        var snapshot = codex([started, userMessage])
        XCTAssertEqual(snapshot.key, SessionKey(source: "codex", sessionID: "01a12fbc-aaaa-bbbb-cccc-0123456789ab"))
        XCTAssertEqual(snapshot.host, .codexDesktop)
        XCTAssertEqual(snapshot.cwd, "/tmp/shot")
        XCTAssertEqual(snapshot.firstPrompt, "Add a share sheet")
        XCTAssertEqual(snapshot.phase, .working)

        snapshot = codex([started, userMessage, exec])
        XCTAssertEqual(snapshot.activity, Activity(verb: "running", detail: "xcodebuild -scheme Shot build"))
        XCTAssertEqual(codex([started, exec, execOut]).activity, .thinking)

        snapshot = codex([started, userMessage, exec, execOut, complete])
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.lastReply, "Share sheet added.")
        XCTAssertEqual(snapshot.phaseSince, Date(timeIntervalSince1970: 1_800_000_009))
        // Bookkeeping after the turn ended does not restart it.
        let tokens = #"{"timestamp":"2027-01-15T08:00:10.000Z","type":"event_msg","payload":{"type":"token_count","info":{}}}"#
        XCTAssertEqual(codex([started, complete, tokens, execOut]).phase, .waiting)
    }

    func testCodexToolsQuestionsAndHelpers() {
        let shell = #"{"type":"response_item","payload":{"type":"function_call","name":"shell","call_id":"c2","arguments":"{\"command\":[\"bash\",\"-lc\",\"git status\"]}"}}"#
        XCTAssertEqual(codex([started, shell]).activity, Activity(verb: "running", detail: "git status"))
        let patch = #"{"type":"response_item","payload":{"type":"custom_tool_call","name":"apply_patch","call_id":"c3","input":"*** Begin Patch"}}"#
        XCTAssertEqual(codex([started, patch]).activity.verb, "editing")
        let delegate = #"{"type":"response_item","payload":{"type":"function_call","namespace":"collaboration","name":"send_message","call_id":"c4","arguments":"{\"target\":\"API Tester\",\"message\":\"go\"}"}}"#
        XCTAssertEqual(codex([started, delegate]).activity, Activity(verb: "delegating", detail: "API Tester"))

        let ask = #"{"type":"response_item","payload":{"type":"function_call","name":"request_user_input_async","call_id":"q1","arguments":"{\"questions\":[]}"}}"#
        XCTAssertEqual(codex([started, ask]).phase, .needsAttention)
        XCTAssertEqual(codex([started, ask, execOut]).phase, .needsAttention, "another call returning does not answer it")
        let answered = #"{"type":"response_item","payload":{"type":"function_call_output","call_id":"q1","output":"B"}}"#
        XCTAssertEqual(codex([started, ask, answered]).phase, .working)

        let helperMeta = #"{"type":"session_meta","payload":{"id":"helper-1","cwd":"/tmp/shot","originator":"codex_work_desktop","source":{"subagent":{"thread_spawn":{}}},"thread_source":"subagent","parent_thread_id":"01a12fbc-aaaa-bbbb-cccc-0123456789ab","agent_role":"API Tester"}}"#
        let helper = codex([started], head: [helperMeta])
        XCTAssertTrue(helper.isSubagent)
        XCTAssertEqual(helper.parentID, "01a12fbc-aaaa-bbbb-cccc-0123456789ab")
        XCTAssertEqual(helper.title, "API Tester")
        XCTAssertEqual(helper.key.sessionID, "helper-1")
        // No session_meta in reach: the id comes from the file name.
        XCTAssertEqual(codex([started], head: [started]).key.sessionID, "01a12fbc-aaaa-bbbb-cccc-0123456789ab")
    }
}

final class TranscriptScoutTests: XCTestCase {
    private func write(_ text: String, to url: URL, age: TimeInterval = 0) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url)
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-age)], ofItemAtPath: url.path)
    }

    func testFindsRecentSessionsAndFollowsThemAsTheyGrow() throws {
        let scratch = try Scratch()
        let home = scratch.url
        let claude = home.appendingPathComponent(".claude/projects/-tmp-proj/11111111-aaaa.jsonl")
        let old = home.appendingPathComponent(".claude/projects/-tmp-proj/22222222-old.jsonl")
        let helper = home.appendingPathComponent(".claude/projects/-tmp-proj/11111111-aaaa/subagents/agent-1.jsonl")
        let codex = home.appendingPathComponent(".codex/sessions/2027/01/15/rollout-2027-01-15T08-00-00-01a12fbc-aaaa-bbbb-cccc-0123456789ab.jsonl")
        let prompt = #"{"type":"user","cwd":"/tmp/proj","message":{"role":"user","content":"Fix the flaky upload test"}}"# + "\n"
        let done = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Done."}]}}"# + "\n"
        try write(prompt, to: claude)
        try write(prompt, to: old, age: 3 * 3600)
        try write(prompt, to: helper)
        try write(#"{"type":"session_meta","payload":{"id":"cx","cwd":"/tmp/shot","originator":"Codex Desktop"}}"# + "\n"
                  + #"{"type":"event_msg","payload":{"type":"task_started"}}"# + "\n", to: codex, age: 60)

        let scout = TranscriptScout(home: home) { _ in }
        var found = scout.scanOnce()
        XCTAssertEqual(found.map(\.key.description), ["claude/11111111-aaaa", "codex/cx"], "newest first; old files and sub-agent files are left out")
        XCTAssertEqual(found[0].phase, .working)
        XCTAssertEqual(found[0].firstPrompt, "Fix the flaky upload test")
        XCTAssertEqual(found[1].host, .codexDesktop)

        // The file grows: the next pass reads the new tail.
        try write(prompt + done, to: claude)
        found = scout.scanOnce()
        XCTAssertEqual(found.first { $0.key.source == "claude" }?.phase, .waiting)
        XCTAssertEqual(found.first { $0.key.source == "claude" }?.lastReply, "Done.")

        // A file that falls out of the window is forgotten.
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-3 * 3600)], ofItemAtPath: codex.path)
        XCTAssertEqual(scout.scanOnce().map(\.key.source), ["claude"])
        try FileManager.default.removeItem(at: claude)
        XCTAssertEqual(scout.scanOnce(), [])
    }

    func testOnlyTheTailOfALongTranscriptIsRead() throws {
        let scratch = try Scratch()
        let file = scratch.url.appendingPathComponent(".claude/projects/p/33333333.jsonl")
        let prompt = #"{"type":"user","message":{"role":"user","content":"The first ask"}}"# + "\n"
        let filler = String(repeating: #"{"type":"assistant","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"tool_use","name":"Read","input":{"file_path":"/tmp/a.swift"}}]}}"# + "\n", count: 400)
        let done = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Finished."}]}}"# + "\n"
        try write(prompt + filler + done, to: file)
        var options = TranscriptScout.Options()
        options.tailBytes = 2048
        let scout = TranscriptScout(home: scratch.url, options: options) { _ in }
        let snapshot = try XCTUnwrap(scout.scanOnce().first)
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.firstPrompt, "The first ask", "from the head of the file")
        XCTAssertEqual(snapshot.lastReply, "Finished.")
    }
}

final class TranscriptMergeTests: XCTestCase {
    private let key = SessionKey(source: "codex", sessionID: "cx")
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    private func snapshot(_ phase: Session.Phase = .working, prompt: String? = "Add a share sheet", reply: String? = nil,
                          activity: Activity = .thinking, key: SessionKey? = nil, subagentOf parent: String? = nil) -> TranscriptSnapshot {
        TranscriptSnapshot(key: key ?? self.key, path: "/h/rollout.jsonl", cwd: "/tmp/shot", host: .codexDesktop, title: nil,
                           firstPrompt: prompt, lastPrompt: prompt, lastReply: reply, phase: phase, activity: activity,
                           updatedAt: now, phaseSince: now, isSubagent: parent != nil, parentID: parent)
    }

    func testATranscriptAloneMakesASession() {
        var store = SessionStore()
        XCTAssertEqual(store.merge([snapshot()], live: false, now: now), [.updated(key)])
        let session = store[key]
        XCTAssertEqual(session?.origin, .transcript)
        XCTAssertEqual(session?.phase, .working)
        XCTAssertEqual(session?.host, .codexDesktop)
        XCTAssertEqual(session?.hostName, "Codex")
        XCTAssertEqual(session?.hostBundleID, "com.openai.codex")
        XCTAssertEqual(session?.title, "shot · Add share sheet")
        XCTAssertEqual(store.merge([snapshot()], now: now), [], "nothing changed, nothing to redraw")
    }

    func testLiveTransitionsAreNewsButTheFirstReadingIsNot() {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(store.merge([snapshot(.waiting, reply: "Done.", activity: .waiting)], now: now), [.becameIdle(key)])
        XCTAssertEqual(store[key]?.lastReply, "Done.")
        XCTAssertEqual(store.merge([snapshot(.working, prompt: "Now add tests")], now: now), [.started(key)])
        XCTAssertEqual(store.merge([snapshot(.needsAttention, prompt: "Now add tests", activity: Activity(verb: "has a question"))], now: now),
                       [.attention(key)])

        var fresh = SessionStore()
        fresh.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(fresh.merge([snapshot(.waiting, activity: .waiting)], live: false, now: now), [.updated(key)],
                       "before the scout is primed nothing is announced")
    }

    func testHooksOutrankTheTranscriptAndOnlyGainDetails() throws {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        // A hook event for the same session takes over.
        let event = try AgentEvent(json: .object([
            "hook_event_name": .string(HookEvent.preToolUse), "_source": .string("codex"), "session_id": .string("cx"),
            "tool_name": .string("Bash"), "tool_input": .object(["command": .string("make")]),
        ]), defaultSource: "codex")
        store.apply(event, now: now)
        XCTAssertEqual(store[key]?.origin, .hooks)
        XCTAssertEqual(store[key]?.activity.verb, "running")

        var later = snapshot(.waiting, reply: "From the transcript", activity: .waiting)
        later.title = "Share sheet"
        XCTAssertEqual(store.merge([later], now: now), [.updated(key)])
        XCTAssertEqual(store[key]?.phase, .working, "the transcript does not overrule live events")
        XCTAssertEqual(store[key]?.customTitle, "Share sheet")
        XCTAssertEqual(store[key]?.lastReply, "From the transcript")
        // The transcript leaving the window does not remove a session hooks are reporting.
        XCTAssertEqual(store.merge([], now: now), [])
        XCTAssertNotNil(store[key])
    }

    func testTranscriptSessionsLeaveWithTheirTranscriptAndRespectDismissal() {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(store.merge([], now: now), [.ended(key)])
        XCTAssertNil(store[key])
        XCTAssertEqual(store.merge([snapshot()], dismissed: [key], now: now), [])
        XCTAssertNil(store[key], "dismissed until it has something new to say")
    }

    func testHelpersAreCountedOnTheirParentNotListed() {
        var store = SessionStore()
        let helper1 = snapshot(key: SessionKey(source: "codex", sessionID: "h1"), subagentOf: "cx")
        let helper2 = snapshot(key: SessionKey(source: "codex", sessionID: "h2"), subagentOf: "cx")
        let idleHelper = snapshot(.waiting, activity: .waiting, key: SessionKey(source: "codex", sessionID: "h3"), subagentOf: "cx")
        store.merge([snapshot(), helper1, helper2, idleHelper], live: false, now: now)
        XCTAssertEqual(store.sessions.count, 1)
        XCTAssertEqual(store[key]?.subagents, 2)
        store.merge([snapshot(), idleHelper], now: now)
        XCTAssertEqual(store[key]?.subagents, 0)
    }
}
