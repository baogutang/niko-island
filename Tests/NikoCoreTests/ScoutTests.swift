final class TranscriptScoutTests: XCTestCase {
    private func write(_ text: String, to url: URL, age: TimeInterval = 0) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url)
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-age)], ofItemAtPath: url.path)
    }

    func testFindsRecentSessionsAndFollowsThemAsTheyGrow() throws {
        let scratch = Scratch()
        let home = scratch.url
        let claude = home.appendingPathComponent(".claude/projects/-tmp-proj/11111111-aaaa.jsonl")
        let old = home.appendingPathComponent(".claude/projects/-tmp-proj/22222222-old.jsonl")
        let helper = home.appendingPathComponent(".claude/projects/-tmp-proj/11111111-aaaa/subagents/agent-1.jsonl")
        let codex = home.appendingPathComponent(".codex/sessions/2027/01/15/rollout-2027-01-15T08-00-00-01a12fbc-aaaa-bbbb-cccc-0123456789ab.jsonl")
        let prompt = #"{"type":"user","cwd":"/tmp/proj","message":{"role":"user","content":"Fix the flaky upload test"}}"# + "\n"
        let done = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Done."}]}}"# + "\n"
        try write(prompt, to: claude)
        try write(prompt, to: old, age: 3 * 3600)
        try write(prompt, to: helper)
        try write(#"{"type":"session_meta","payload":{"id":"cx","cwd":"/tmp/shot","originator":"Codex Desktop"}}"# + "\n"
                  + #"{"type":"event_msg","payload":{"type":"task_started"}}"# + "\n", to: codex, age: 60)

        let scout = TranscriptScout(home: home) { _ in }
        var found = scout.scanOnce()
        XCTAssertEqual(found.map(\.key.description), ["claude/11111111-aaaa", "codex/cx"], "newest first; old files and sub-agent files are left out")
        XCTAssertEqual(found[0].phase, .working)
        XCTAssertEqual(found[0].firstPrompt, "Fix the flaky upload test")
        XCTAssertEqual(found[1].host, .codexDesktop)

        // The file grows: the next pass reads the new tail.
        try write(prompt + done, to: claude)
        found = scout.scanOnce()
        XCTAssertEqual(found.first { $0.key.source == "claude" }?.phase, .waiting)
        XCTAssertEqual(found.first { $0.key.source == "claude" }?.lastReply, "Done.")

        // A file that falls out of the window is forgotten.
        try FileManager.default.setAttributes([.modificationDate: Date().addingTimeInterval(-3 * 3600)], ofItemAtPath: codex.path)
        XCTAssertEqual(scout.scanOnce().map(\.key.source), ["claude"])
        try FileManager.default.removeItem(at: claude)
        XCTAssertEqual(scout.scanOnce(), [])
    }

    func testOnlyTheTailOfALongTranscriptIsRead() throws {
        let scratch = Scratch()
        let file = scratch.url.appendingPathComponent(".claude/projects/p/33333333.jsonl")
        let prompt = #"{"type":"user","message":{"role":"user","content":"The first ask"}}"# + "\n"
        let filler = String(repeating: #"{"type":"assistant","message":{"role":"assistant","stop_reason":"tool_use","content":[{"type":"tool_use","name":"Read","input":{"file_path":"/tmp/a.swift"}}]}}"# + "\n", count: 400)
        let done = #"{"type":"assistant","message":{"role":"assistant","stop_reason":"end_turn","content":[{"type":"text","text":"Finished."}]}}"# + "\n"
        try write(prompt + filler + done, to: file)
        var options = TranscriptScout.Options()
        options.tailBytes = 2048
        let scout = TranscriptScout(home: scratch.url, options: options) { _ in }
        let snapshot = try XCTUnwrap(scout.scanOnce().first)
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.firstPrompt, "The first ask", "from the head of the file")
        XCTAssertEqual(snapshot.lastReply, "Finished.")
    }
}

final class TranscriptMergeTests: XCTestCase {
    private let key = SessionKey(source: "codex", sessionID: "cx")
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    private func snapshot(_ phase: Session.Phase = .working, prompt: String? = "Add a share sheet", reply: String? = nil,
                          activity: Activity = .thinking, key: SessionKey? = nil, subagentOf parent: String? = nil) -> TranscriptSnapshot {
        TranscriptSnapshot(key: key ?? self.key, path: "/h/rollout.jsonl", cwd: "/tmp/shot", host: .codexDesktop, title: nil,
                           firstPrompt: prompt, lastPrompt: prompt, lastReply: reply, phase: phase, activity: activity,
                           updatedAt: now, phaseSince: now, isSubagent: parent != nil, parentID: parent)
    }

    func testATranscriptAloneMakesASession() {
        var store = SessionStore()
        XCTAssertEqual(store.merge([snapshot()], live: false, now: now), [.updated(key)])
        let session = store[key]
        XCTAssertEqual(session?.origin, .transcript)
        XCTAssertEqual(session?.phase, .working)
        XCTAssertEqual(session?.host, .codexDesktop)
        XCTAssertEqual(session?.hostName, "Codex")
        XCTAssertEqual(session?.hostBundleID, "com.openai.codex")
        XCTAssertEqual(session?.title, "shot · Add share sheet")
        XCTAssertEqual(store.merge([snapshot()], now: now), [], "nothing changed, nothing to redraw")
    }

    func testLiveTransitionsAreNewsButTheFirstReadingIsNot() {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(store.merge([snapshot(.waiting, reply: "Done.", activity: .waiting)], now: now), [.becameIdle(key)])
        XCTAssertEqual(store[key]?.lastReply, "Done.")
        XCTAssertEqual(store.merge([snapshot(.working, prompt: "Now add tests")], now: now), [.started(key)])
        XCTAssertEqual(store.merge([snapshot(.needsAttention, prompt: "Now add tests", activity: Activity(verb: "has a question"))], now: now),
                       [.attention(key)])

        var fresh = SessionStore()
        fresh.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(fresh.merge([snapshot(.waiting, activity: .waiting)], live: false, now: now), [.updated(key)],
                       "before the scout is primed nothing is announced")
    }

    func testHooksOutrankTheTranscriptAndOnlyGainDetails() throws {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        // A hook event for the same session takes over.
        let event = try AgentEvent(json: .object([
            "hook_event_name": .string(HookEvent.preToolUse), "_source": .string("codex"), "session_id": .string("cx"),
            "tool_name": .string("Bash"), "tool_input": .object(["command": .string("make")]),
        ]), defaultSource: "codex")
        store.apply(event, now: now)
        XCTAssertEqual(store[key]?.origin, .hooks)
        XCTAssertEqual(store[key]?.activity.verb, "running")

        var later = snapshot(.waiting, reply: "From the transcript", activity: .waiting)
        later.title = "Share sheet"
        XCTAssertEqual(store.merge([later], now: now), [.updated(key)])
        XCTAssertEqual(store[key]?.phase, .working, "the transcript does not overrule live events")
        XCTAssertEqual(store[key]?.customTitle, "Share sheet")
        XCTAssertEqual(store[key]?.lastReply, "From the transcript")
        // The transcript leaving the window does not remove a session hooks are reporting.
        XCTAssertEqual(store.merge([], now: now), [])
        XCTAssertNotNil(store[key])
    }

    func testTranscriptSessionsLeaveWithTheirTranscriptAndRespectDismissal() {
        var store = SessionStore()
        store.merge([snapshot()], live: false, now: now)
        XCTAssertEqual(store.merge([], now: now), [.ended(key)])
        XCTAssertNil(store[key])
        XCTAssertEqual(store.merge([snapshot()], dismissed: [key], now: now), [])
        XCTAssertNil(store[key], "dismissed until it has something new to say")
    }

    func testHelpersAreCountedOnTheirParentNotListed() {
        var store = SessionStore()
        let helper1 = snapshot(key: SessionKey(source: "codex", sessionID: "h1"), subagentOf: "cx")
        let helper2 = snapshot(key: SessionKey(source: "codex", sessionID: "h2"), subagentOf: "cx")
        let idleHelper = snapshot(.waiting, activity: .waiting, key: SessionKey(source: "codex", sessionID: "h3"), subagentOf: "cx")
        store.merge([snapshot(), helper1, helper2, idleHelper], live: false, now: now)
        XCTAssertEqual(store.sessions.count, 1)
        XCTAssertEqual(store[key]?.subagents, 2)
        store.merge([snapshot(), idleHelper], now: now)
        XCTAssertEqual(store[key]?.subagents, 0)
    }
}

/// ZCode keeps sessions in a database; the fixture has the tables and columns
/// of the real one (ZCode 3.15), with made-up rows.
final class ZCodeSessionsTests: XCTestCase {
    private let now = Date(timeIntervalSince1970: 1_800_000_000)
    private var ms: Int64 { Int64(now.timeIntervalSince1970 * 1000) }

    private func makeHome(_ scratch: Scratch) throws -> (home: URL, db: SQLiteDB) {
        let home = scratch.file("home")
        try FileManager.default.createDirectory(at: home.appendingPathComponent(".zcode/cli/db"), withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: home.appendingPathComponent(".zcode/v2"), withIntermediateDirectories: true)
        let db = try SQLiteDB(path: ZCodeSessions.databasePath(home: home))
        try db.execute("""
            CREATE TABLE session (id TEXT PRIMARY KEY, parent_id TEXT, directory TEXT, title TEXT, time_created INTEGER,
                                  time_updated INTEGER, time_archived INTEGER, task_type TEXT);
            CREATE TABLE message (id TEXT PRIMARY KEY, session_id TEXT, time_created INTEGER, time_updated INTEGER, data TEXT, sequence INTEGER);
            CREATE TABLE part (id TEXT PRIMARY KEY, message_id TEXT, session_id TEXT, time_created INTEGER, time_updated INTEGER, data TEXT, sequence INTEGER);
            """)
        return (home, db)
    }

    private func session(_ db: SQLiteDB, _ id: String, parent: String? = nil, directory: String, title: String, quietFor seconds: Double, archived: Bool = false) throws {
        try db.run("INSERT INTO session VALUES (?, ?, ?, ?, ?, ?, ?, ?)", [
            .text(id), parent.map { .text($0) } ?? .null, .text(directory), .text(title), .integer(ms - 3_600_000),
            .integer(ms - Int64(seconds * 1000)), archived ? .integer(ms) : .null, .text(parent == nil ? "interactive" : "subagent_child"),
        ])
    }

    private var counter = 0
    private func message(_ db: SQLiteDB, _ sessionID: String, _ data: String, parts: [String]) throws {
        counter += 1
        let id = "msg_\(counter)"
        try db.run("INSERT INTO message VALUES (?, ?, ?, ?, ?, ?)", [.text(id), .text(sessionID), .integer(ms), .integer(ms), .text(data), .integer(Int64(counter))])
        for (index, part) in parts.enumerated() {
            try db.run("INSERT INTO part VALUES (?, ?, ?, ?, ?, ?, ?)",
                       [.text("\(id)_p\(index)"), .text(id), .text(sessionID), .integer(ms), .integer(ms), .text(part), .integer(Int64(index))])
        }
    }

    func testSessionsAreReadFromZCodesDatabase() throws {
        let scratch = Scratch()
        let (home, db) = try makeHome(scratch)
        let user = #"{"role":"user","time":{"created":1800000000000}}"#
        // A turn in full swing: asked, answered with a tool call that is still running.
        try session(db, "sess_busy", directory: "/Users/me/projects/atlas", title: "Fix the upload retry", quietFor: 3)
        try message(db, "sess_busy", user, parts: [#"{"type":"text","text":"Fix the flaky upload retry test"}"#])
        try message(db, "sess_busy", #"{"role":"assistant","finish":"tool-calls","time":{"created":1,"completed":2}}"#,
                    parts: [#"{"type":"text","text":"Let me look."}"#, #"{"type":"tool","tool":"Read","state":{"status":"completed","input":{"file_path":"/a/Upload.swift"},"output":"…"}}"#])
        try message(db, "sess_busy", #"{"role":"assistant","time":{"created":3}}"#,
                    parts: [#"{"type":"step-start"}"#, #"{"type":"text","text":"Running the tests now."}"#,
                            #"{"type":"tool","tool":"Bash","state":{"status":"running","input":{"command":"swift test --filter Upload","description":"run"},"output":"big"}}"#])
        // A helper of that session.
        try session(db, "sess_helper", parent: "sess_busy", directory: "/Users/me/projects/atlas", title: "Explore the retry code", quietFor: 5)
