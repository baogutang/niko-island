    private func codex(_ lines: [String], head: [String]? = nil, quietFor: TimeInterval = 2) -> TranscriptSnapshot {
        let meta = CodexTranscript.meta(path: codexPath, head: jsonl(head ?? [metaLine, started, userMessage]))
        return CodexTranscript.snapshot(path: codexPath, meta: meta, tail: jsonl(lines), tailIsWholeFile: true,
                                        modified: now.addingTimeInterval(-quietFor), now: now)!
    }

    func testCodexTurnIsFollowedStepByStep() {
        var snapshot = codex([started, userMessage])
        XCTAssertEqual(snapshot.key, SessionKey(source: "codex", sessionID: "01a12fbc-aaaa-bbbb-cccc-0123456789ab"))
        XCTAssertEqual(snapshot.host, .codexDesktop)
        XCTAssertEqual(snapshot.cwd, "/tmp/shot")
        XCTAssertEqual(snapshot.firstPrompt, "Add a share sheet")
        XCTAssertEqual(snapshot.phase, .working)

        snapshot = codex([started, userMessage, exec])
        XCTAssertEqual(snapshot.activity, Activity(verb: "running", detail: "xcodebuild -scheme Shot build"))
        XCTAssertEqual(codex([started, exec, execOut]).activity, .thinking)

        snapshot = codex([started, userMessage, exec, execOut, complete])
        XCTAssertEqual(snapshot.phase, .waiting)
        XCTAssertEqual(snapshot.lastReply, "Share sheet added.")
        XCTAssertEqual(snapshot.phaseSince, Date(timeIntervalSince1970: 1_800_000_009))
        // Bookkeeping after the turn ended does not restart it.
        let tokens = #"{"timestamp":"2027-01-15T08:00:10.000Z","type":"event_msg","payload":{"type":"token_count","info":{}}}"#
        XCTAssertEqual(codex([started, complete, tokens, execOut]).phase, .waiting)
    }

    func testCodexToolsQuestionsAndHelpers() {
        let shell = #"{"type":"response_item","payload":{"type":"function_call","name":"shell","call_id":"c2","arguments":"{\"command\":[\"bash\",\"-lc\",\"git status\"]}"}}"#
        XCTAssertEqual(codex([started, shell]).activity, Activity(verb: "running", detail: "git status"))
        let patch = #"{"type":"response_item","payload":{"type":"custom_tool_call","name":"apply_patch","call_id":"c3","input":"*** Begin Patch"}}"#
