import Foundation

/// Generated shell entry points under `~/.niko-island/bin/` (PROTOCOLS §3, §4).
public enum Shims {
    public static let userSectionBegin = "# >>> niko-island user section >>>"
    public static let userSectionEnd = "# <<< niko-island user section <<<"

    static let defaultUserSection = """
    # Print your own status line here; this block survives reinstalls.
    # The JSON the agent sent is in "$input", for example:
    #   printf '%s' "$input" | jq -r '.model.display_name'
    """

    /// POSIX sh shim that locates the real bridge inside the app bundle.
    /// Lookup order: fixed paths → cache file → Spotlight → give up silently.
    public static func bridgeShim(paths: NikoPaths) -> String {
        """
        #!/bin/sh
        # niko-bridge shim — generated by Niko Island \(NikoVersion.current); rewritten on every install.
        # Runs the bridge binary that ships inside the app bundle. If the app is
        # gone, this exits 0 without a word so agent hooks keep working.
        dir=\(paths.shellPath(paths.bin))
        cache="$dir/.bridge-cache"
        miss="$dir/.bridge-miss"
        rel="Contents/Helpers/niko-bridge"
        bin=""

        if [ -n "${NIKO_BRIDGE_BIN:-}" ] && [ -x "${NIKO_BRIDGE_BIN:-}" ]; then
            bin="$NIKO_BRIDGE_BIN"
        fi
        if [ -z "$bin" ]; then
            for candidate in "/Applications/Niko Island.app/$rel" "$HOME/Applications/Niko Island.app/$rel"; do
                if [ -x "$candidate" ]; then
                    bin="$candidate"
                    break
                fi
            done
        fi
        if [ -z "$bin" ] && [ -r "$cache" ]; then
            candidate="$(head -n 1 "$cache" 2>/dev/null)"
            if [ -n "$candidate" ] && [ -x "$candidate" ]; then
                bin="$candidate"
            fi
        fi
        if [ -z "$bin" ]; then
            # Spotlight is slow: after a miss, do not ask again for an hour.
            if [ -n "$(find "$miss" -mmin -60 2>/dev/null)" ]; then
                exit 0
            fi
            app="$(mdfind 'kMDItemCFBundleIdentifier == "\(NikoVersion.bundleIdentifier)"' 2>/dev/null | head -n 1)"
            if [ -n "$app" ] && [ -x "$app/$rel" ]; then
                bin="$app/$rel"
                # Grouped so a failed redirect (directory gone) stays quiet and non-fatal.
                { printf '%s\\n' "$bin" > "$cache"; } 2>/dev/null
            else
                { touch "$miss"; } 2>/dev/null
                exit 0
            fi
        fi

        "$bin" "$@"
        status=$?
        # Only a deliberate deny (2) is passed on. Any failure of ours is success to the agent.
        if [ "$status" -eq 2 ]; then
            exit 2
        fi
        exit 0

        """
    }

    /// Bash statusline wrapper: caches rate limits, then runs the user's section.
    public static func statuslineScript(paths: NikoPaths, userSection: String? = nil) -> String {
        let section = (userSection ?? defaultUserSection).trimmingCharacters(in: .newlines)
        return """
        #!/bin/bash
        # niko-statusline — generated by Niko Island \(NikoVersion.current).
        # Everything outside the user section below is rewritten on install.
        input=$(cat)
        bridge=\(paths.shellPath(paths.bridgeShim))
        if [ -x "$bridge" ]; then
            # Backgrounded so the status line never waits on us.
            (printf '%s' "$input" | "$bridge" --task statusline-cache --cache-file \(paths.shellPath(paths.rateLimitCache)) >/dev/null 2>&1 &)
        fi
        \(userSectionBegin)
        \(section)
        \(userSectionEnd)
        exit 0

        """
    }

    /// The text between the user-section markers of an existing script, if both are present.
    public static func extractUserSection(from script: String) -> String? {
        guard let begin = script.range(of: userSectionBegin),
              let end = script.range(of: userSectionEnd, range: begin.upperBound..<script.endIndex) else {
            return nil
        }
        return String(script[begin.upperBound..<end.lowerBound]).trimmingCharacters(in: .newlines)
    }

    /// User section that chains to a statusline command the user already had.
    public static func chainedUserSection(originalCommand: String) -> String {
        """
        # Your previous status line command, kept as it was:
        printf '%s' "$input" | \(originalCommand)
        """
    }

    /// Convenience launcher so `~/.niko-island/bin/niko-island uninstall` works from a shell.
    public static func cliShim(appExecutable: String) -> String {
        """
        #!/bin/sh
        # niko-island CLI launcher — generated by Niko Island \(NikoVersion.current).
        app=\(ShellQuote.single(appExecutable))
        if [ ! -x "$app" ]; then
            app="/Applications/Niko Island.app/Contents/MacOS/niko-island"
        fi
        if [ ! -x "$app" ]; then
            echo "niko-island: the app is not installed (expected $app)" >&2
            exit 1
        fi
        exec "$app" "$@"

        """
    }

    /// Hook command for Claude-dialect agents (INTEGRATIONS: wrapped so a missing shim is a no-op).
    /// With `propagateDeny` the shim's exit status (0 or 2) becomes the hook's,
    /// for agents that only understand exit codes.
    public static func hookCommand(paths: NikoPaths, source: String, extraArguments: [String] = [],
                                   propagateDeny: Bool = false) -> String {
        let shim = paths.shellPath(paths.bridgeShim)
        let arguments = (["--source", source] + extraArguments).joined(separator: " ")
        let body = propagateDeny
            ? "[ -x \(shim) ] || exit 0; \(shim) \(arguments)"
            : "[ -x \(shim) ] && \(shim) \(arguments); exit 0"
        return "/bin/sh -c " + ShellQuote.single(body)
    }

    public static func statuslineCommand(paths: NikoPaths) -> String {
        let script = paths.shellPath(paths.statuslineScript)
        return "/bin/sh -c " + ShellQuote.single("[ -x \(script) ] && exec \(script); exit 0")
    }

    public struct WriteReport: Sendable, Equatable {
        public var written: [String] = []
    }

    /// Writes the shims (0755) and the bridge cache. Preserves an existing statusline user section.
    @discardableResult
    public static func install(paths: NikoPaths, bridgeBinary: String?, appExecutable: String?,
                               statuslineUserSection: String? = nil, overrideUserSection: Bool = false) throws -> WriteReport {
        try SecureDirectory.ensureTree(paths)
        var report = WriteReport()
        func put(_ text: String, _ url: URL, mode: mode_t) throws {
            guard AtomicFile.write(Data(text.utf8), to: url.path, mode: mode) else {
                throw IngressError.system("write \(url.path)", errno)
            }
            report.written.append(url.path)
        }
        try put(bridgeShim(paths: paths), paths.bridgeShim, mode: 0o755)
        let existing = overrideUserSection ? nil
            : (try? String(contentsOf: paths.statuslineScript, encoding: .utf8)).flatMap(extractUserSection)
        try put(statuslineScript(paths: paths, userSection: existing ?? statuslineUserSection),
                paths.statuslineScript, mode: 0o755)
        if let bridgeBinary {
            try put(bridgeBinary + "\n", paths.bridgeCache, mode: 0o600)
            unlink(paths.bridgeMiss.path)
        }
        if let appExecutable {
            try put(cliShim(appExecutable: appExecutable), paths.bin.appendingPathComponent("niko-island"), mode: 0o755)
        }
        return report
    }

    /// Removes only the files `install` creates.
    public static func remove(paths: NikoPaths) {
        for url in [paths.bridgeShim, paths.statuslineScript, paths.bridgeCache, paths.bridgeMiss,
                    paths.bin.appendingPathComponent("niko-island")] {
            unlink(url.path)
        }
    }

    /// Where the bridge binary lives relative to the running executable:
    /// inside the bundle (`Contents/Helpers`) or next to it for `swift run`.
    public static func locateBridgeBinary(mainExecutable: String = CommandLine.arguments.first ?? "") -> String? {
        var candidates: [String] = []
        let bundle = Bundle.main.bundleURL
        if bundle.pathExtension == "app" {
            candidates.append(bundle.appendingPathComponent("Contents/Helpers/niko-bridge").path)
        }
        if let executable = Bundle.main.executableURL {
            candidates.append(executable.deletingLastPathComponent().appendingPathComponent("niko-bridge").path)
            candidates.append(executable.deletingLastPathComponent().deletingLastPathComponent()
                .appendingPathComponent("Helpers/niko-bridge").path)
        }
        if !mainExecutable.isEmpty {
            candidates.append(URL(fileURLWithPath: mainExecutable).deletingLastPathComponent()
                .appendingPathComponent("niko-bridge").path)
        }
        return candidates.first { FileManager.default.isExecutableFile(atPath: $0) }
    }
}
